$ns.AddNamespace('w', $nsUri)

function Get-ParagraphText([System.Xml.XmlNode]$p) {
    $texts = @($p.SelectNodes('.//w:t', $ns) | ForEach-Object { $_.InnerText })
    return ($texts -join '')
}

function New-Run([System.Xml.XmlDocument]$doc, [string]$text) {
    $r = $doc.CreateElement('w', 'r', $nsUri)
    $t = $doc.CreateElement('w', 't', $nsUri)
    if ($text -match '^\s' -or $text -match '\s$' -or $text.Contains('  ')) {
        $spaceAttr = $doc.CreateAttribute('xml', 'space', 'http://www.w3.org/XML/1998/namespace')
        $spaceAttr.Value = 'preserve'
        $t.Attributes.Append($spaceAttr) | Out-Null
    }
    $t.InnerText = $text
    $r.AppendChild($t) | Out-Null
    return $r
}

function Set-ParagraphText([System.Xml.XmlNode]$p, [string]$text) {
    $keep = @()
    foreach ($child in @($p.ChildNodes)) {
        if ($child.LocalName -eq 'pPr') {
            $keep += $child
        }
    }
    while ($p.HasChildNodes) {
        $p.RemoveChild($p.FirstChild) | Out-Null
    }
    foreach ($node in $keep) {
        $imported = $xml.ImportNode($node, $true)
        $p.AppendChild($imported) | Out-Null
    }
    $p.AppendChild((New-Run $xml $text)) | Out-Null
}

function New-Paragraph([string]$text, [string]$style = $null) {
    $p = $xml.CreateElement('w', 'p', $nsUri)
    if ($style) {
        $pPr = $xml.CreateElement('w', 'pPr', $nsUri)
        $pStyle = $xml.CreateElement('w', 'pStyle', $nsUri)
        $valAttr = $xml.CreateAttribute('w', 'val', $nsUri)
        $valAttr.Value = $style
        $pStyle.Attributes.Append($valAttr) | Out-Null
        $pPr.AppendChild($pStyle) | Out-Null
        $p.AppendChild($pPr) | Out-Null
    }
    $p.AppendChild((New-Run $xml $text)) | Out-Null
    return $p
}

function Find-Paragraph([string]$text) {
    foreach ($p in $xml.SelectNodes('//w:body/w:p', $ns)) {
        if ((Get-ParagraphText $p) -eq $text) {
            return $p
        }
    }
    throw "Paragraph not found: $text"
}

function Find-ParagraphLike([string]$text) {
    foreach ($p in $xml.SelectNodes('//w:body/w:p', $ns)) {
        if ((Get-ParagraphText $p) -like "*$text*") {
            return $p
        }
    }
    throw "Paragraph not found like: $text"
}

function Insert-After([System.Xml.XmlNode]$anchor, [string[]]$texts, [string]$style = $null) {
    $current = $anchor
    foreach ($text in $texts) {
        $p = New-Paragraph $text $style
        $current.ParentNode.InsertAfter($p, $current) | Out-Null
        $current = $p
    }
    return $current
}

function Insert-Before([System.Xml.XmlNode]$anchor, [string[]]$texts, [string]$style = $null) {
    $current = $anchor
    foreach ($text in $texts) {
        $p = New-Paragraph $text $style
        $current.ParentNode.InsertBefore($p, $current) | Out-Null
        $current = $p
    }
    return $current
}

